import math

def suma(a, b):
    return a + b

def resta(a, b):
    return a - b

def raiz_cuadrada(a):
    return math.sqrt(a)

def cuadrado(a):
    return a ** 2

def division(a, b):
    return a / b

def potencia(a, b):
    return a ** b

def valor_absoluto(a):
    return abs(a)

def doble(a):
    return a * 2

def multiplicacion(a, b):
    return a * b

def mitad(a):
    return a / 2

def modulo(a, b):
    return a % b

